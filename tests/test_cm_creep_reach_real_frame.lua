tests['§3 SHIPPED: every centre it may return with count >= 2 is out of cast range'] = function()
    local J, bot, _, fx = load_frame()
    local X = rf.load_hero('crystal_maiden')
    J.IsModeTurbo = function() return true end
    J.IsSoakCandidate = function() return false end
    local nSearch = X.cm_GetCreepAoESearchRange(N_CAST_RANGE, NOVA_RADIUS)

    local tCreeps = enemy_creeps(fx, subject_team(fx))
    local loc = bot:GetLocation()

    local tWant = { [1] = 805.9, [2] = 904.5, [3] = 925.1, [4] = 1152.4, [5] = 1312.3 }
    for k = 1, 5 do
        local d = nearest_centre(tCreeps, loc.x, loc.y, NOVA_RADIUS, k)
        close_to(d, tWant[k], 0.1, 'nearest centre covering >= ' .. k)
    end
    assert(nearest_centre(tCreeps, loc.x, loc.y, NOVA_RADIUS, 6) == nil,
        'no centre anywhere covers 6 of them')

    -- What the shipped ring can and cannot hand back on this frame.
    for k = 2, 4 do
        local d = nearest_centre(tCreeps, loc.x, loc.y, NOVA_RADIUS, k)
        assert(d <= nSearch, 'count >= ' .. k .. ' is inside the 1157 search ring')
        assert(d > N_CAST_RANGE,
            'and outside the 732 cast ring by ' .. string.format('%.1f', d - N_CAST_RANGE))
    end
    local d5 = nearest_centre(tCreeps, loc.x, loc.y, NOVA_RADIUS, 5)
    assert(d5 > nSearch, 'count >= 5 is beyond even the shipped ring: ' .. d5)

    -- The overshoot in the units the fix is about: the cheapest 2-creep centre
    -- is 172.5 beyond her reach, the cheapest 4-creep one is 420.4 beyond.
    close_to(nearest_centre(tCreeps, loc.x, loc.y, NOVA_RADIUS, 2) - N_CAST_RANGE,
        172.5, 0.1, 'overshoot at the count>=2 sites')
    close_to(nearest_centre(tCreeps, loc.x, loc.y, NOVA_RADIUS, 4) - N_CAST_RANGE,
        420.4, 0.1, 'overshoot at the count>=4 sites')
end

