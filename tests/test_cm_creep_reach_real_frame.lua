--- The enemy lane creeps on the frame, in CM's terms: team 4 is neutrals and
--- her own team's creeps are not what `FindAoELocation(true, ...)` looks at.
local function enemy_creeps(fx, subj_team)
    local out = {}
    for _, c in ipairs(fx.creeps or {}) do
        if c.team ~= 4 and c.team ~= subj_team then
            out[#out + 1] = { x = c.x, y = c.y }
        end
    end
    return out
end

local function subject_team(fx)
    for _, u in ipairs(fx.units) do
        if u.name == fx.self then return u.team end
    end
    error('subject not in the fixture')
end

local function close_to(got, want, tol, what)
    assert(got ~= nil and math.abs(got - want) <= tol,
        string.format('%s: got %s, want %s +-%s', what, tostring(got), want, tol))
end

