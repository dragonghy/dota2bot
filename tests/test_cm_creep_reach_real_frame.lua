tests['§4 the bound is over ALL qualifying centres, not the nearest one only'] = function()
    local _, bot, _, fx = load_frame()
    local tCreeps = enemy_creeps(fx, subject_team(fx))
    local loc = bot:GetLocation()

    -- The claim of §3 is a MINIMUM, so it holds for whatever the engine picks.
    -- Demonstrated rather than asserted: sample the whole shipped search disk
    -- on a coarse lattice and check that no point in it both covers >= 2 and
    -- sits inside the cast ring.  (A lattice can only miss such a point, and
    -- the exact solver above already says there is none -- the two instruments
    -- disagreeing is what this node exists to catch.)
    local nInRangeWithCreeps = 0
    for gx = -1157, 1157, 17 do
        for gy = -1157, 1157, 17 do
            local qx, qy = loc.x + gx, loc.y + gy
            if dist(loc.x, loc.y, qx, qy) <= N_CAST_RANGE
                and coverage(tCreeps, qx, qy, NOVA_RADIUS) >= 1 then
                nInRangeWithCreeps = nInRangeWithCreeps + 1
            end
        end
    end
    assert(nInRangeWithCreeps == 0,
        'a castable point covering an enemy creep was found on the lattice: '
        .. nInRangeWithCreeps)
end

