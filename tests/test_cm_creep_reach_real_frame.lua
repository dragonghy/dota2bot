--
-- `bot:FindAoELocation( bEnemies, bHeroes, vBase, nMaxDistanceFromBase,
-- nRadius, fTimeInFuture, nMaxHealth )` may return ANY point within
-- `nMaxDistanceFromBase` of `vBase` (docs/BOT_API_REFERENCE.md:1366).  Which
-- one it picks among equally good centres is an engine internal this repo
-- cannot read.  So the question is NOT asked as "what point does the engine
-- return" -- it is asked with a quantifier that makes the engine's choice
-- irrelevant:
--
--     over the REAL creep positions on this frame, how far from CM is the
--     NEAREST point that covers at least k of them?
--
-- If even the nearest qualifying centre is out of cast range, then EVERY
-- qualifying centre is, and whatever the engine hands back with `count >= k`
-- is a point she cannot cast at.  That is a bound, not a model of the engine.
--
-- THE READING (section 3, and it is the point of this file)
--
--     nearest legal centre covering >= 1 enemy creep :   805.9
--                                       >= 2          :   904.5
--                                       >= 3          :   925.1
--                                       >= 4          :  1152.4
--                                       >= 5          :  1312.3
--                                       >= 6          :  none
--     the ring she may cast into                      :   732
--     the ring the SHIPPED code searches               :  1157
--     the ring the ARMED code searches ('cmqreach')    :   732
--
-- Read off those two columns:
--   * SHIPPED can return a centre with count 2, 3 or 4 (5 is beyond even the
--     wide ring), and every such centre is between 904.5 and 1157 from her --
--     that is 172.5 to 425 units BEYOND the 732 she may cast into.  There is no
--     tie-break under which the shipped search hands back a castable creep
--     point on this frame.
--   * ARMED returns count 0: the nearest centre covering even ONE enemy creep
--     is 805.9 away, outside the 732 ring.  Every `count >= N` creep site is
--     false, so the armed side does not cast Nova on the wave here at all.
--
-- That is the fix's own claim -- "armed casts on waves no more often than
-- shipped, and never relocates a cast that was already legal" -- observed on a
-- real frame rather than argued.  It does NOT show a gain; see section 6.
--
-- THE SOLVER IS EXACT, AND IS PINNED AS SUCH
--
-- For a fixed radius r, the nearest point of an intersection of disks to C is
-- C itself (when feasible), or a point where one constraint is active (the
-- projection of C onto that circle), or a vertex where two are (an intersection
-- of two circles).  Those three families are the whole candidate set, so the
-- minimum below is exact -- no grid, no tolerance ladder.  Cross-checked
-- offline against a 2-unit brute-force grid on this very frame: 904.86 /
-- 925.18 / 1152.48 for k = 2/3/4, each a hair above the exact value, which is
-- the direction a grid must err.  Section 5 pins the solver on synthetic inputs
-- with hand-computable answers, because a solver checked only on the frame it
-- was written for is checked against nothing (the M4/M8 lesson from
-- tests/test_aoe_result_field_names.lua, twice paid for now).
--
-- WHAT THIS FILE DOES NOT CLAIM (section 6, measured where possible)
--
--   * NOT that the armed side is better here.  It says the armed side casts
--     nothing on this frame and the shipped side can only aim at a point it
--     cannot reach.  Which of those two is worth more is what the engine does
--     with an out-of-range order, and that is unreadable from the bot VM.
--   * NOT a firing claim.  Whether execution REACHES a creep return site needs
--     creep health (`nCanKillCreeps...` filters on it, and every creep site
--     also wants a valid weakest lane creep) and the mode predicates
--     `IsFarming` / `IsPushing` / `IsDefending` -- none of which the dump
--     carries.  Section 6 states this as a fact about the fixture, not as a
--     property of the hero.
--   * NOT that the creep positions are the ones she cast at.  They are a
--     sample.  This dump was taken at `-creep-interval 0.5` (the wave farm's
--     default is 3.0), so the sample sits dt = 0.0 from the instant -- the
