tests['§3b the hurt post-filter does NOT rescue it: the count survives, the point stays unreachable'] = function()
    -- Before the eight sites read it, the hurt result passes through
    -- `J.GetInLocLaneCreepCount( bot, 1600, nRadius, targetloc ) <= 2 -> count = 0`.
    -- On this frame that filter passes: all four creeps the nearest 4-covering
    -- centre covers are also within 1600 of her, so the count is not zeroed and
    -- the three `>= 4` sites return a point 420.4 beyond her cast range.
    local _, bot, _, fx = load_frame()
    local tCreeps = enemy_creeps(fx, subject_team(fx))
    local loc = bot:GetLocation()

    local d, qx, qy = nearest_centre(tCreeps, loc.x, loc.y, NOVA_RADIUS, 4)
    close_to(d, 1152.4, 0.1, 'the nearest 4-covering centre')

    local nInLoc = 0
    for _, p in ipairs(tCreeps) do
        if dist(qx, qy, p.x, p.y) <= NOVA_RADIUS + EPS
            and dist(loc.x, loc.y, p.x, p.y) <= 1600 then
            nInLoc = nInLoc + 1
        end
    end
    assert(nInLoc == 4, 'creeps within 425 of the point AND 1600 of her: ' .. nInLoc)
    assert(nInLoc > 2, 'so the <= 2 filter does not zero the count')
end

