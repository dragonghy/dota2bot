tests['§5 solver: one point -- the nearest centre is on the line, at d - r'] = function()
    local pts = { { x = 1000, y = 0 } }
    local d = nearest_centre(pts, 0, 0, 425, 1)
    close_to(d, 575, 1e-6, 'single point at 1000, radius 425')
    -- Inside the disk already: the answer must be 0, not d - r.
    close_to(nearest_centre({ { x = 100, y = 0 } }, 0, 0, 425, 1), 0, 1e-6,
        'a point already within r of C')
end

tests['§5 solver: two points -- the lens vertex, hand-computed'] = function()
    -- Points at (0, +-300): a radius-425 disk covers both iff its centre is
    -- within 425 of each, so the legal set is the lens of the two circles,
    -- whose left vertex sits at x = -sqrt(425^2 - 300^2).  C far to the left
    -- makes that vertex the nearest legal centre.
    local pts = { { x = 0, y = 300 }, { x = 0, y = -300 } }
    local h = math.sqrt(425 * 425 - 300 * 300)
    local d = nearest_centre(pts, -5000, 0, 425, 2)
    close_to(d, 5000 - h, 1e-6, 'nearest point of the lens from far left')
    -- ...and covering just ONE of them is cheaper, which is the ordering every
    -- k-threshold claim in §3 depends on.
    assert(nearest_centre(pts, -5000, 0, 425, 1) < d, 'k=1 is never worse than k=2')
end

tests['§5 solver: k beyond what any disk can cover returns nil, not a number'] = function()
    -- Three points pairwise 900 apart: no radius-425 disk covers two of them
    -- (900 > 850), so k = 2 is infeasible ANYWHERE.  A solver that clamped
    -- instead of refusing would answer some finite distance here.
    local s = 900
    local pts = {
        { x = 0, y = 0 }, { x = s, y = 0 }, { x = s / 2, y = s * math.sqrt(3) / 2 },
    }
    assert(nearest_centre(pts, 0, 0, 425, 2) == nil, 'k=2 is infeasible at 900 apart')
    close_to(nearest_centre(pts, 0, 0, 425, 1), 0, 1e-6, 'k=1 is C itself')
    -- 849 apart: now a covering disk exists, and it is the midpoint.
    local ok = { { x = 0, y = 0 }, { x = 849, y = 0 } }
    close_to(nearest_centre(ok, 424.5, 0, 425, 2), 0, 1e-6, 'k=2 at 849 apart, C at the midpoint')
end

tests['§5 solver: the projection family is load-bearing, not decoration'] = function()
    -- Two points 800 apart, C far away on the perpendicular bisector.  The
    -- nearest 2-covering centre is a LENS VERTEX; the nearest 1-covering centre
    -- is a PROJECTION onto one circle.  A candidate set missing the projections
    -- would over-report the k=1 answer -- which is the exact defect the offline
    -- Python first draft had (it read 1157 where the truth was 1152.4), caught
    -- only by a brute-force grid.  This node is that catch, made permanent.
    local pts = { { x = -400, y = 3000 }, { x = 400, y = 3000 } }
    local d1 = nearest_centre(pts, 0, 0, 425, 1)
    local want1 = math.sqrt(400 * 400 + 3000 * 3000) - 425
    close_to(d1, want1, 1e-6, 'k=1 is the projection onto the nearer circle')
    local d2 = nearest_centre(pts, 0, 0, 425, 2)
    -- lens vertex on the near side: (0, 3000 - sqrt(425^2 - 400^2))
    close_to(d2, 3000 - math.sqrt(425 * 425 - 400 * 400), 1e-6, 'k=2 is the lens vertex')
    assert(d2 > d1, 'and it is farther, as it must be')
end

