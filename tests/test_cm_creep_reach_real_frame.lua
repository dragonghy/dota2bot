tests['§3b the HURT search is the priceable one, and its count on this frame is 4'] = function()
    -- nMaxHealth = 0 for the hurt search, so no creep health is needed and §3's
    -- numbers ARE its numbers.  Its two thresholds in the source are >= 4 and
