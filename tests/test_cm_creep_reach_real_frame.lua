local EPS = 1e-6

-- =====================================================================
-- The exact solver (see header).  Kept in this file on purpose: it is a
-- reading instrument, not shipped logic, and section 5 is its calibration.
-- =====================================================================

local function dist(ax, ay, bx, by)
    local dx, dy = ax - bx, ay - by
    return math.sqrt(dx * dx + dy * dy)
end

--- How many of `tPts` a radius-`r` disk centred at (qx, qy) covers.
local function coverage(tPts, qx, qy, r)
    local n = 0
    for _, p in ipairs(tPts) do
        if dist(qx, qy, p.x, p.y) <= r + EPS then n = n + 1 end
    end
    return n
end

--- Every candidate centre the exact minimum can sit on (header: C itself, the
--- projection of C onto each circle, and each pair of circles' intersections).
local function candidates(tPts, cx, cy, r)
    local out = { { x = cx, y = cy } }
    for _, p in ipairs(tPts) do
        local d = dist(cx, cy, p.x, p.y)
        if d > EPS then
            local s = math.max(0.0, d - r) / d
            out[#out + 1] = { x = cx + (p.x - cx) * s, y = cy + (p.y - cy) * s }
        end
    end
    for i = 1, #tPts do
        for j = i + 1, #tPts do
            local a, b = tPts[i], tPts[j]
            local dx, dy = b.x - a.x, b.y - a.y
            local d = math.sqrt(dx * dx + dy * dy)
            if d > EPS and d <= 2 * r then
                local h = math.sqrt(math.max(0.0, r * r - (d / 2) * (d / 2)))
                local mx, my = (a.x + b.x) / 2, (a.y + b.y) / 2
                local ux, uy = -dy / d, dx / d
                out[#out + 1] = { x = mx + ux * h, y = my + uy * h }
                out[#out + 1] = { x = mx - ux * h, y = my - uy * h }
            end
        end
    end
    return out
end

--- Distance from (cx, cy) to the NEAREST centre of a radius-`r` disk that
--- covers at least `k` of `tPts`.  nil when no such centre exists anywhere.
--- The engine's own `nMaxDistanceFromBase` is applied by the CALLER, by
--- comparing this distance against the search radius: minimising |q - C| means
--- that constraint can never be active at the optimum, it can only exclude it.
local function nearest_centre(tPts, cx, cy, r, k)
    local best, bx, by
    for _, q in ipairs(candidates(tPts, cx, cy, r)) do
        if coverage(tPts, q.x, q.y, r) >= k then
            local d = dist(cx, cy, q.x, q.y)
            if best == nil or d < best then best, bx, by = d, q.x, q.y end
        end
    end
    return best, bx, by
end

